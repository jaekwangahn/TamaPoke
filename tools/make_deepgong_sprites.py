"""Pack the five Figma Noti sprites into transparent RGB565 frames."""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 64

with (ROOT / "deepgong_sprites.h").open("w", encoding="utf-8") as out:
    out.write("// Generated by tools/make_deepgong_sprites.py.\n#pragma once\n#include <stdint.h>\n\n")
    out.write(f"constexpr int NOTI_SIZE = {SIZE};\n")
    out.write("constexpr uint16_t NOTI_TRANSPARENT = 0xF81F;\n")
    out.write("static const uint16_t NOTI_SPRITES[5][NOTI_SIZE * NOTI_SIZE] = {\n")
    for level in range(1, 6):
        with Image.open(ROOT / f"tools/assets/noti_lv{level}.png") as source:
            sprite = source.convert("RGBA")
        sprite = sprite.crop(sprite.getbbox())
        sprite.thumbnail((SIZE, SIZE), Image.Resampling.LANCZOS)
        frame = Image.new("RGBA", (SIZE, SIZE))
        frame.paste(sprite, ((SIZE - sprite.width) // 2, SIZE - sprite.height))
        pixels = frame.tobytes()
        out.write("  {\n")
        for i in range(0, len(pixels), SIZE * 4):
            row = pixels[i:i + SIZE * 4]
            colors = []
            for r, g, b, a in zip(row[0::4], row[1::4], row[2::4], row[3::4]):
                color = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
                if color == 0xF81F:
                    color = 0xF81E
                colors.append(f"0x{color if a >= 128 else 0xF81F:04X}")
            for column in range(0, SIZE, 16):
                out.write("    " + ", ".join(colors[column:column + 16]) + ",\n")
        out.write("  },\n")
    out.write("};\n")
