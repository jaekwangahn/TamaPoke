"""Convert the Deepgong campus art to an RGB565 firmware asset."""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 233

with Image.open(ROOT / "tools/assets/deepgong_campus.png") as source:
    pixels = source.convert("RGB").resize((SIZE, SIZE), Image.Resampling.LANCZOS).tobytes()
    colors = [(r >> 3) << 11 | (g >> 2) << 5 | (b >> 3) for r, g, b in zip(pixels[0::3], pixels[1::3], pixels[2::3])]

with (ROOT / "deepgong_campus.h").open("w", encoding="utf-8") as out:
    out.write("// Generated by tools/make_deepgong_campus.py.\n#pragma once\n#include <stdint.h>\n\n")
    out.write(f"constexpr int DEEPGONG_CAMPUS_SIZE = {SIZE};\n")
    out.write("static const uint16_t DEEPGONG_CAMPUS[] = {\n")
    for i in range(0, len(colors), 12):
        out.write("  " + ", ".join(f"0x{c:04X}" for c in colors[i:i + 12]) + ",\n")
    out.write("};\n")
