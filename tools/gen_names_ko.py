#!/usr/bin/env python3
"""Generate Korean species names and a font character list from PokéAPI CSVs.

Run from any directory: python3 tools/gen_names_ko.py
The upstream revision is pinned so rebuilding produces the same names.
Downloaded source CSVs are cached under tools/downloads/pokeapi-ko/.
"""
import csv
from pathlib import Path
import urllib.request


ROOT = Path(__file__).resolve().parents[1]
POKEAPI_REV = "8a92bfa7dab2f12b84b5d151562f9857c133ff30"
SOURCE = f"https://raw.githubusercontent.com/PokeAPI/pokeapi/{POKEAPI_REV}/data/v2/csv"
CACHE = ROOT / "tools" / "downloads" / "pokeapi-ko" / POKEAPI_REV
DEX_MAX = 1025


def rows(name):
    path = CACHE / f"{name}.csv"
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(f"{SOURCE}/{name}.csv", timeout=90) as response:
            data = response.read()
        path.write_bytes(data)
    with path.open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def main():
    languages = {row["id"]: row["identifier"] for row in rows("languages")}
    names = {
        int(row["pokemon_species_id"]): row["name"]
        for row in rows("pokemon_species_names")
        if languages.get(row["local_language_id"]) == "ko"
        and 1 <= int(row["pokemon_species_id"]) <= DEX_MAX
    }
    missing = sorted(set(range(1, DEX_MAX + 1)) - names.keys())
    if missing or any(not name.strip() for name in names.values()):
        raise SystemExit(f"Missing Korean species names: {missing}")
    output = [
        "#pragma once\n\n",
        "// GENERATED by tools/gen_names_ko.py; do not edit manually.\n",
        f"// Official Korean species names from PokéAPI, revision {POKEAPI_REV}.\n",
        "// Source: data/v2/csv/pokemon_species_names.csv (language identifier ko).\n",
        "static const char *const DEX_NAME_KO[] = {\n",
        "  nullptr,  // 0: unused\n",
    ]
    for number in range(1, DEX_MAX + 1):
        name = names[number].replace("\\", "\\\\").replace('"', '\\"')
        output.append(f'  "{name}",  // {number}\n')
    output.extend(["};\n", f"#define DEX_NAME_KO_COUNT {DEX_MAX}\n"])
    (ROOT / "dex_names_ko.h").write_text("".join(output), encoding="utf-8")
    chars = "".join(sorted(set("".join(names.values())), key=ord))
    (ROOT / "tools" / "ko_name_chars.txt").write_text(chars + "\n", encoding="utf-8")
    print(f"Korean names: {len(names)} species, {len(chars)} distinct characters")


if __name__ == "__main__":
    main()
